"""Builds assets/css/fonts.css with the fonts embedded as data URIs.

usage:  python3 -I demos/build_fonts.py        (from the elixir-website folder)

Embedding means the fonts also load when index.html is opened straight from
the disk (Chrome blocks font files on file:// pages). The source files and
their SIL Open Font License texts stay in assets/fonts/.
"""
import base64
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
FONTS = SITE / "assets/fonts"
faces = [("Poppins", w, f"poppins-{w}.woff2") for w in (400, 500, 600, 700)]
faces += [("Open Sauce Sans", 400, "open-sauce-sans-400.woff")]
faces += [("Open Sauce Sans", w, f"open-sauce-sans-{w}.woff2") for w in (500, 600, 700)]
faces += [("Source Serif 4", 400, "source-serif-4-400-italic.woff2", "italic")]

css = ["/* Generated by demos/build_fonts.py -- do not edit by hand.",
       "   Poppins, Open Sauce Sans and Source Serif 4, SIL Open Font License 1.1 (see assets/fonts/). */"]
for face in faces:
    family, weight, name = face[:3]
    style = face[3] if len(face) > 3 else "normal"
    data = (FONTS / name).read_bytes()
    fmt, mime = ("woff2", "font/woff2") if name.endswith(".woff2") else ("woff", "font/woff")
    head = data[:4]
    assert head in (b"wOF2", b"wOFF"), f"{name} is not a web font ({head!r})"
    b64 = base64.b64encode(data).decode()
    css.append(f'@font-face{{font-family:"{family}";font-weight:{weight};font-style:{style};font-display:swap;'
               f'src:url(data:{mime};base64,{b64}) format("{fmt}")}}')
out = SITE / "assets/css/fonts.css"
out.write_text("\n".join(css) + "\n")
print(f"wrote {out.relative_to(SITE)} ({out.stat().st_size // 1024} KB, {len(faces)} faces)")
